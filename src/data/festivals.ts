/** All festival cards in calendar order for the unfiltered year export. */
export function festivalsForYearPack(): Festival[] {
  return [...FESTIVALS].sort(
    (a, b) => FESTIVAL_MONTHS.indexOf(a.month) - FESTIVAL_MONTHS.indexOf(b.month),
  );
}
